/** Short codes for PostHog — never send raw exception text from user mutations. */
function mealPlanGenerateFailureReason(e: unknown): string {
  const msg = e instanceof Error ? e.message : String(e);
  if (/no recipes available/i.test(msg)) return "empty_recipe_pool";
  if (/timeout|timed out|network|fetch failed|failed to fetch/i.test(msg)) {
    return "network";
  }
  if (/convex|mutation|unauthorized|forbidden|not found/i.test(msg)) {
    return "backend_error";
  }
  if (/invalid|validation|must be|required/i.test(msg)) {
    return "validation_error";
  }
  return "unknown_error";
}

function mealPlanErrorMessage(e: unknown): string {
  const msg = e instanceof Error ? e.message : String(e);
  if (msg.includes(MEAL_PLAN_ERRORS.PREMIUM_REQUIRED_MULTIPLE_MEAL_PLANS)) {
    return "Multiple active meal plans are a premium feature. Upgrade to create another plan.";
  }
  if (msg.includes(MEAL_PLAN_ERRORS.PREMIUM_REQUIRED_LEFTOVER_INGREDIENTS)) {
    return "Leftover-ingredient management is a premium feature. Upgrade to enable it.";
  }
  if (
    msg.includes(MEAL_PLAN_ERRORS.PREMIUM_REQUIRED_ADVANCED_MEAL_PLAN_CONTROLS)
  ) {
    return "Custom start dates and day lengths are premium controls.";
  }
  if (msg.includes(MEAL_PLAN_ERRORS.PREMIUM_REQUIRED_HOUSEHOLD_PREFERENCES)) {
    return "Household preference filtering is a premium feature.";
  }
  if (msg.includes(MEAL_PLAN_ERRORS.HOUSEHOLD_PREFERENCES_NO_RECIPES)) {
    return "No recipes match the selected member preferences. Try toggling fewer members or loosening restrictions.";
  }
  if (msg.includes(MEAL_PLAN_ERRORS.PREMIUM_REQUIRED_QUICK_MEALS)) {
    return "Quick meal targeting is a premium feature.";
  }
  if (msg.includes(MEAL_PLAN_ERRORS.QUICK_MEALS_NO_RECIPES)) {
    return "Not enough recipes match that quick-meals preset. Try Automatic or a lighter preset.";
  }
  if (msg.includes("No eligible recipes matched your current constraints")) {
    return "We couldn't find enough eligible meals with your current filters. Try loosening member preferences, quick-meal settings, or recency constraints.";
  }
  return msg;
}
