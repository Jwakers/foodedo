function formatPlanRangeShort(start: number | undefined, end: number): string {
  const fmt = (ms: number) =>
    new Date(ms).toLocaleDateString(undefined, {
      day: "numeric",
      month: "short",
      timeZone: "UTC",
    });
  if (start !== undefined) return `${fmt(start)} – ${fmt(end)}`;
  return fmt(end);
}

